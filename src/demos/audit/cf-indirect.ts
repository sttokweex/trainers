import type { LegacyDemo } from '@/engine/types'
import * as H from '@/demos/helpers'
const { dEl, dBtn, dShell, dField, dSelect, dRange, kpi, fmt, money, num, pct, th,
        barsH, barsV, lineC, stackRow, chartBox, legend, sv, mkSort, mkMatch, mkSteps,
        mkTree, calcShell, bindAll, ACC, ACC_KEYS, accLabel } = H as any

export const cfIndirect: LegacyDemo = root => {
  const L = [
    { n:'Прибыль до налогообложения', v:4800000, w:'Точка старта. Считается методом начисления, поэтому к деньгам отношения пока не имеет.' },
    { n:'+ Амортизация ОС и НМА', v:2100000, w:'Неденежный расход: прибыль уменьшил, деньги не трогал. Возвращаем обратно.' },
    { n:'+ Начисленные резервы (сомнительные долги, отпуска)', v:850000, w:'Тоже неденежные: обязательство или оценка признаны, деньги не двигались.' },
    { n:'− Прибыль от продажи основных средств', v:-320000, w:'Прибыль сидит в финрезультате, но сами деньги от продажи относятся к инвестиционному разделу. Убираем, чтобы не задвоить.' },
    { n:'+ Проценты к уплате', v:640000, w:'Возвращаем, чтобы показать их отдельной строкой (классификация зависит от учётной политики).' },
    { n:'− Рост дебиторской задолженности', v:-2400000, w:'Выручка признана, но деньги не пришли — оборотный капитал «съел» их.' },
    { n:'− Рост запасов', v:-1150000, w:'Деньги превратились в склад.' },
    { n:'+ Рост кредиторской задолженности', v:1700000, w:'Поставщики прокредитовали компанию: расход признан, деньги ещё не ушли.' },
    { n:'− Налог на прибыль уплаченный', v:-900000, w:'Фактическая уплата, а не начисление.' },
  ];
  mkSteps(root, 'От прибыли к операционному денежному потоку', {
    steps: L.map((x, i) => ({ ...x, note:x.w })),
    render(panel, s, i){
      const tb = dEl('table', 'tbl');
      tb.innerHTML = '<tr><th>Строка</th><th>Сумма</th><th>Накопленный поток</th></tr>';
      let run = 0;
      L.forEach((x, j) => {
        if (j > i) return;
        run += x.v;
        const tr = document.createElement('tr');
        if (j === i) tr.className = 'hl';
        tr.innerHTML = '<td>' + x.n + '</td><td class="n">' + fmt(x.v) + '</td><td class="n">' + fmt(run) + '</td>';
        tb.appendChild(tr);
      });
      panel.appendChild(tb);
      const k = dEl('div', 'kpis');
      kpi(k, 'Прибыль до налогообложения', money(L[0].v), 'по данным ОФР');
      kpi(k, 'Накопленный денежный поток', money(run), i === L.length - 1 ? 'итог операционной деятельности' : 'после этого шага', 'acc');
      if (i === L.length - 1) kpi(k, 'Разрыв', money(run - L[0].v), 'настолько деньги отличаются от прибыли', 'yel');
      panel.appendChild(k);
    }
  });
}
