import { bindAll, calcShell, dEl, dField, kpi, money, num } from '@/demos/helpers'
import type { LegacyDemo } from '@/engine/types'

/** Чистые активы: показатель, от которого зависят дивиденды и сама жизнь общества. */
export const netAssets: LegacyDemo = (root) => {
  const { form, out } = calcShell(root, 'Чистые активы и что из них следует',
    'Чистые активы считаются по методике Минфина: активы за вычетом задолженности учредителей по вкладам, ' +
    'минус обязательства за вычетом доходов будущих периодов, признанных в связи с государственной помощью ' +
    'и безвозмездным получением имущества.')

  const assets = dField(form, 'Итого активы (строка 1600), ₽', 120000000, { step:1000000 })
  const founders = dField(form, 'в том числе задолженность учредителей по вкладам, ₽', 0, { step:100000 })
  const liab = dField(form, 'Итого обязательства (разделы IV + V), ₽', 96000000, { step:1000000 })
  const dbp = dField(form, 'в том числе доходы будущих периодов от госпомощи, ₽', 1500000, { step:100000 })
  const uk = dField(form, 'Уставный капитал, ₽', 10000000, { step:100000 })
  const divid = dField(form, 'Планируемые дивиденды, ₽', 8000000, { step:500000 })

  const kpis = dEl('div', 'kpis')
  const verdict = dEl('div', 'tree-out ok')
  const note = dEl('div', 'demo-note')
  out.appendChild(kpis)
  out.appendChild(verdict)
  out.appendChild(note)

  const kNa = kpi(kpis, 'Чистые активы', '', '', 'acc')
  const kVs = kpi(kpis, 'Сравнение с уставным капиталом', '', '')
  const kAfter = kpi(kpis, 'Чистые активы после дивидендов', '', '')

  function calc(): void {
    const na = (num(assets) - num(founders)) - (num(liab) - num(dbp))
    const after = na - num(divid)
    const gap = na - num(uk)

    kNa.set(money(na), '(' + money(num(assets)) + ' − ' + money(num(founders)) + ') − (' +
      money(num(liab)) + ' − ' + money(num(dbp)) + ')', na < 0 ? 'kpi red' : 'kpi acc')
    kVs.set(gap >= 0 ? 'выше на ' + money(gap) : 'ниже на ' + money(-gap),
      'уставный капитал ' + money(num(uk)), gap >= 0 ? 'kpi grn' : 'kpi red')
    kAfter.set(money(after), 'если дивиденды будут выплачены', after < num(uk) ? 'kpi red' : 'kpi grn')

    let cls: string
    let head: string
    let text: string
    if (na < 0) {
      cls = 'bad'
      head = 'Отрицательные чистые активы'
      text = 'Обязательства превышают активы. Это прямой индикатор для МСА 570: нужен анализ руководства о непрерывности деятельности, ' +
        'проверка его модели денежных потоков и оценка достаточности раскрытий. Выплата дивидендов в такой ситуации незаконна.'
    } else if (na < num(uk)) {
      cls = 'bad'
      head = 'Чистые активы меньше уставного капитала'
      text = 'Если такая ситуация сохраняется по окончании второго и каждого последующего финансового года, закон требует ' +
        'уменьшить уставный капитал до величины чистых активов либо принять решение о ликвидации. Аудитор проверяет, ' +
        'выполнило ли общество это требование, и оценивает влияние на непрерывность деятельности и на раскрытия.'
    } else if (after < num(uk)) {
      cls = 'q'
      head = 'Дивиденды выплатить нельзя в полном объёме'
      text = 'Сейчас чистые активы в норме, но после выплаты они опустятся ниже уставного капитала — а это одно из ограничений ' +
        'на распределение прибыли. Максимальная безопасная сумма: ' + money(Math.max(0, na - num(uk))) + '.'
    } else {
      cls = 'ok'
      head = 'Ограничений по этому основанию нет'
      text = 'Чистые активы превышают уставный капитал и остаются выше него после выплаты. Проверьте остальные ограничения: ' +
        'полная оплата уставного капитала, отсутствие признаков банкротства, решение общего собрания.'
    }
    verdict.className = 'tree-out ' + cls
    verdict.innerHTML = '<b>' + head + '</b>' + text

    note.innerHTML = 'Чистые активы — это тот же собственный капитал, но посчитанный по правилам, которые не дают «дорисовать» его ' +
      'за счёт неоплаченных вкладов. Для аудитора это ещё и быстрый индикатор: показатель ниже уставного капитала почти всегда означает ' +
      'накопленный убыток, а значит — вопросы к непрерывности деятельности, к восстанавливаемости отложенных налоговых активов ' +
      'и к раскрытиям в пояснениях.'
  }

  bindAll(form, calc)
}
