import { dEl, mkSteps } from '@/demos/helpers'
import type { LegacyDemo } from '@/engine/types'

interface Step {
  n: string
  q: string
  how: string
  /** Как шаг выглядит на трёх разных операциях. */
  cases: [string, string, string]
  note?: string
}

/** Универсальный алгоритм: как составить проводку, не зная её наизусть. */
export const entryLogic: LegacyDemo = (root) => {
  const OPS = [
    'Купили товар у поставщика за 600 000 ₽ с отсрочкой',
    'Выплатили зарплату сотрудникам 400 000 ₽ с расчётного счёта',
    'Получили аванс от покупателя 240 000 ₽',
  ]

  const STEPS: Step[] = [
    { n:'Шаг 1. Что реально произошло',
      q:'Опишите событие словами, без счетов. Что пришло в компанию и что ушло?',
      how:'Пока не понятно событие, счета подбирать бессмысленно. Большинство ошибок новичка рождается здесь: человек ищет «проводку для документа», а не описывает факт хозяйственной жизни.',
      cases:[
        'Пришёл товар. Денег не отдавали — возник долг перед поставщиком.',
        'Ушли деньги со счёта. Долг перед работниками уменьшился.',
        'Пришли деньги. Возникла обязанность поставить товар.',
      ],
      note:'Проверьте себя вопросом: «что изменилось в имуществе и в долгах?» Если ответа нет — события не было, и проводки быть не должно.' },
    { n:'Шаг 2. Какие два объекта затронуты',
      q:'Назовите ровно два объекта учёта. Их всегда минимум два — в этом и есть двойная запись.',
      how:'Объект — это актив, обязательство, капитал, доход или расход. Подбирайте не счёт, а тип объекта: «товар» и «долг поставщику», а не «41» и «60».',
      cases:[
        'Актив «товары» + обязательство «долг поставщику».',
        'Актив «деньги» + обязательство «долг перед персоналом».',
        'Актив «деньги» + обязательство «аванс покупателя».',
      ] },
    { n:'Шаг 3. Что с каждым объектом: больше или меньше',
      q:'По каждому из двух объектов ответьте: он увеличился или уменьшился?',
      how:'Это единственное, что нужно решить содержательно. Дальше работает механика.',
      cases:[
        'Товары ↑ (стало больше). Долг поставщику ↑ (стало больше).',
        'Деньги ↓ (стало меньше). Долг перед персоналом ↓ (стало меньше).',
        'Деньги ↑. Обязательство перед покупателем ↑.',
      ] },
    { n:'Шаг 4. Применяем правило сторон',
      q:'Активы и расходы растут по дебету. Обязательства, капитал и доходы растут по кредиту. Уменьшение — наоборот.',
      how:'Достаточно запомнить одну строчку: <b>«всё, что слева в уравнении А + Расходы = О + К + Доходы, растёт по дебету»</b>. Остальное выводится.',
      cases:[
        'Товары ↑ → дебет. Долг поставщику ↑ → кредит.',
        'Деньги ↓ → кредит. Долг перед персоналом ↓ → дебет.',
        'Деньги ↑ → дебет. Обязательство ↑ → кредит.',
      ] },
    { n:'Шаг 5. Подставляем счета и проверяем',
      q:'Теперь и только теперь открываем план счетов и подставляем номера.',
      how:'Проверка готовой проводки: сумма по дебету равна сумме по кредиту, тип операции определяется (А+А−, П+П−, А+П+, А−П−), и получившееся сальдо выглядит правдоподобно.',
      cases:[
        '<b>Дт 41 Кт 60</b> — 600 000. Тип А+П+: валюта баланса выросла.',
        '<b>Дт 70 Кт 51</b> — 400 000. Тип А−П−: валюта баланса уменьшилась.',
        '<b>Дт 51 Кт 62.АВ</b> — 240 000. Тип А+П+: выручки здесь нет, она появится при отгрузке.',
      ],
      note:'Если по счёту получилось «обратное» сальдо (например, кредитовое по счёту 41), проводка почти наверняка составлена неверно.' },
  ]

  mkSteps<Step>(root, 'Как составить любую проводку: пять шагов', {
    steps: STEPS,
    render(panel, s) {
      panel.appendChild(dEl('h6', null, s.n))
      panel.appendChild(dEl('div', 'sort-q', s.q))
      panel.appendChild(dEl('div', 'demo-note', s.how))
      const tb = dEl('table', 'tbl')
      tb.innerHTML = '<tr><th>Операция</th><th>На этом шаге</th></tr>' +
        OPS.map((op, i) => '<tr><td>' + op + '</td><td>' + s.cases[i] + '</td></tr>').join('')
      panel.appendChild(tb)
    },
  })
}
