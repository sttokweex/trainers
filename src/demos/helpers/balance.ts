/**
 * Справочник статей баланса: из каких счетов собирается строка, какими
 * проводками она наполняется, что по ней проверяет аудитор.
 *
 * Коды строк приведены по привычной форме. С отчётности за 2025 год состав
 * форм задаёт ФСБУ 4/2023 — на проекте сверяйтесь с действующей формой,
 * логика «строка = набор сальдо» при этом не меняется.
 */

export interface BalanceEntry {
  /** Дебет. */
  d: string
  /** Кредит. */
  k: string
  /** Что за операция. */
  t: string
}

export interface BalanceLine {
  code: string
  name: string
  /** Раздел баланса. */
  section: 'I' | 'II' | 'III' | 'IV' | 'V'
  side: 'A' | 'P'
  /** Как строка собирается из сальдо счетов. */
  formula: string
  /** Счета, участвующие в строке. */
  accounts: string[]
  what: string
  entries: BalanceEntry[]
  checks: string[]
  errors: string[]
  /** Какой стандарт задаёт правила. */
  std?: string
}

