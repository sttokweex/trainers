import type { Question } from './types'

/**
 * Короткая подсказка не раскрывает ответ, а напоминает удобный план атаки.
 * Явная подсказка из контента всегда имеет приоритет; fallback нужен, чтобы в
 * большом банке не оставались вопросы без первой зацепки.
 */
export function questionHint(question: Pick<Question, 'type' | 'hint'>): string {
  if (question.hint?.trim()) return question.hint.trim()
  switch (question.type) {
    case 'output':
      return 'Разберите код по шагам: сначала синхронная часть, затем очереди микрозадач и таймеров. Запишите вывод по строкам.'
    case 'choice':
      return 'Сначала сформулируйте правило, затем проверьте каждый вариант отдельно. Ищите условия, при которых ответ перестаёт быть верным.'
    case 'code':
      return 'Начните с контракта функции: входы, выход, ошибки и граничные случаи. После этого оцените сложность и только затем пишите код.'
    case 'manual':
      return 'Ответьте как на реальном собеседовании: назовите решение, компромисс и один способ проверить его на практике.'
    case 'num':
      return 'Выпишите формулу и единицы измерения, подставьте числа по шагам и округлите только в самом конце.'
    case 'theory':
      return 'Постройте ответ по схеме: что это → как работает → когда применять → какие компромиссы и ошибки бывают.'
  }
}
